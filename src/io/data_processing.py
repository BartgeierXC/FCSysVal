def postprocess_sim_df(config: ValidationConfig, df: pd.DataFrame) -> pd.DataFrame:
    """
    Postprocesses the simulation DataFrame to match the output source DataFrame.
    Optionally applies conversion_factors defined in the sim config's
    output_configuration to each output column (excluding time).
    """
    df.columns = ['time'] + config.data_source.output_variables
    df = df.drop_duplicates(subset='time')
    df = df.set_index('time')

    # Apply conversion_factors from sim config output_configuration if present
    sim_cfg = parse_config(str(config.sim_config.config_path)) or {}
    output_cfg = (sim_cfg.get("simulation_setup") or {}).get("output_configuration") or {}
    conversion_factors = output_cfg.get("conversion_factors")

    if conversion_factors is not None:
        n_factors = len(conversion_factors)
        n_cols = len(df.columns)
        if n_factors != n_cols:
            raise ValueError(
                f"postprocess_sim_df: len(conversion_factors)={n_factors} does not match "
                f"number of output columns={n_cols} (output_variables: {list(df.columns)})"
            )
        df = df.mul(np.asarray(conversion_factors, dtype=float), axis=1)

    return df


def calc_err_metrics(sim_df: pd.DataFrame, source_df: pd.DataFrame) -> pd.DataFrame:
    """
    Calculates error metrics between the simulation DataFrame and the source DataFrame.
    Every column in the simulation DataFrame is compared to the corresponding column in the source DataFrame.
    Return R2 score, mean absolute error, and mean relative error for each column.
    Returns a DataFrame with the error metrics.
    """
    from sklearn.metrics import r2_score, mean_absolute_error

    metrics = {}
    for col in sim_df.columns:
        if col in source_df.columns:
            sim_col = sim_df[col].values
            source_col = source_df[col].values

            # Calculate R2 score
            r2 = r2_score(source_col, sim_col)

            # Calculate mean absolute error
            mae = mean_absolute_error(source_col, sim_col)

            # Calculate mean relative error
            mre = np.mean(np.abs((source_col - sim_col) / source_col)) * 100 if np.any(source_col) else np.nan

            metrics[col] = {
                'R2': r2,
                'MAE': mae,
                'MRE (%)': mre
            }

    return pd.DataFrame(metrics).T


def calc_transient_err_metrics(
    sim_df: pd.DataFrame,
    source_df: pd.DataFrame,
    window: int | None = None,
    return_timeseries: bool = False,
):
    """
    Calculates dynamic (transient) error metrics between the simulation DataFrame and the
    source DataFrame for cycle/ramp experiments with prescribed gradients, i.e. without
    grouping to quasi-stationary points.

    Every column in the simulation DataFrame is compared to the corresponding column in the
    source DataFrame. Rows are assumed to already be aligned on a common time base (same
    convention as `calc_err_metrics`), e.g. because both DataFrames were produced from the
    same sample-and-hold / resampled timeline.

    For each column, computes pointwise absolute error (sim - source) and relative error (%)
    time series, and summarizes them with:
    - R2: coefficient of determination
    - MAE: mean absolute error over the whole window
    - MRE (%): mean relative error over the whole window
    - RMSE: root mean squared error
    - Peak_AE: peak (maximum) absolute error
    - Peak_RE (%): peak (maximum) absolute relative error
    - IAE: integrated absolute error (trapezoidal integration of |abs_err| over the index)
    - rIAE: IAE normalized by the integrated absolute source trajectory (dimensionless);
      NaN if the source integral is zero

    Parameters
    ----------
    sim_df, source_df : pd.DataFrame
        Simulation and source (measured) trajectories, aligned row-wise.
    window : int, optional
        If given, additionally computes rolling MAE and rolling peak absolute error time
        series per column using a rolling window of this many samples.
    return_timeseries : bool, default False
        If True, returns a tuple `(summary_df, timeseries_dict)` where `timeseries_dict`
        maps each compared column name to a DataFrame with columns `abs_err`, `rel_err`,
        and (if `window` is given) `rolling_mae`, `rolling_peak_ae`, indexed like the
        input DataFrames. If False, returns only `summary_df`.

    Returns
    -------
    pd.DataFrame or tuple[pd.DataFrame, dict[str, pd.DataFrame]]
        Summary error metrics DataFrame (one row per compared column), and, if
        `return_timeseries=True`, a dict of per-column error time series.
    """
    from sklearn.metrics import r2_score, mean_absolute_error, mean_squared_error

    if not sim_df.index.equals(source_df.index):
        # Evaluate at the source timestamps: pick the nearest simulation sample.
        sim_sorted = sim_df.sort_index()
        pos = sim_sorted.index.get_indexer(source_df.index, method='nearest')
        sim_df = sim_sorted.iloc[pos].set_axis(source_df.index)

    metrics = {}
    timeseries = {}
    for col in sim_df.columns:
        if col in source_df.columns:
            sim_col = sim_df[col].values
            source_col = source_df[col].values

            abs_err = sim_col - source_col
            with np.errstate(divide='ignore', invalid='ignore'):
                rel_err = np.where(source_col != 0, abs_err / source_col * 100, np.nan)

            r2 = r2_score(source_col, sim_col)
            mae = mean_absolute_error(source_col, sim_col)
            mre = np.nanmean(np.abs(rel_err)) if np.any(source_col) else np.nan
            rmse = np.sqrt(mean_squared_error(source_col, sim_col))
            peak_ae = np.max(np.abs(abs_err))
            peak_re = np.nanmax(np.abs(rel_err)) if np.any(source_col) else np.nan
            t = np.asarray(sim_df.index, dtype=float)
            iae = np.trapezoid(np.abs(abs_err), x=t)
            iae_ref = np.trapezoid(np.abs(source_col), x=t)
            riae = 100 * iae / iae_ref if iae_ref != 0 else np.nan

            metrics[col] = {
                'R2': r2,
                'MAE': mae,
                'MRE (%)': mre,
                'RMSE': rmse,
                'Peak_AE': peak_ae,
                'Peak_RE (%)': peak_re,
                'IAE': iae,
                'rIAE (%)': riae,
            }

            col_ts = pd.DataFrame({'abs_err': abs_err, 'rel_err': rel_err}, index=sim_df.index)
            if window is not None:
                col_ts['rolling_mae'] = col_ts['abs_err'].abs().rolling(window).mean()
                col_ts['rolling_peak_ae'] = col_ts['abs_err'].abs().rolling(window).max()
                col_ts['rolling_mre'] = col_ts['rel_err'].abs().rolling(window).mean()
                col_ts['rolling_peak_re'] = col_ts['rel_err'].abs().rolling(window).max()
            timeseries[col] = col_ts

    summary_df = pd.DataFrame(metrics).T

    if return_timeseries:
        return summary_df, timeseries
    return summary_df


def group_trigger_data(
    config: ValidationConfig,
    df: pd.DataFrame,
    reset_index: bool = True,
    group_duplicates: bool = False,
    rtol: float = 1e-2,
    return_std: bool = False,
) -> pd.DataFrame | tuple[pd.DataFrame, pd.DataFrame]:
    """
    Groups the data in the DataFrame according to the group configuration.
    Uses trigger values for grouping.
    Filter for rows with 'trigger_steps' consecutive steps of the same trigger value.
    Each group is calculated from the last `group_time` index units of the step, i.e.
    seconds on an elapsed time axis. `trigger_steps` only selects the steps.

    Parameters
    ----------
    reset_index : bool, default True
        If True, reset the DataFrame index to a default integer range after
        grouping. If False, keep the original source time index.
    group_duplicates : bool, default False
        If True, rows in the grouped result whose trigger-column values are
        equal within the relative tolerance `rtol` (anywhere in the result,
        not only consecutive rows) are merged to their column-wise mean and
        the duplicates removed.
    rtol : float, default 1e-2
        Relative tolerance used when ``group_duplicates=True``.  Two trigger
        values ``a`` and ``b`` are considered equal when
        ``|a - b| <= rtol * |b|``.
    return_std : bool, default False
        If True, also return the sample standard deviation of each window
        (Bessel correction, ``ddof=1``) as a second DataFrame aligned with
        the grouped means. Type A uncertainty of the mean is then
        ``u_A = std / sqrt(n)`` with the number of samples n in the window.
    """
    group_time = config.group_config.group_time
    trigger_steps = config.group_config.trigger_steps
    trigger = config.group_config.trigger
    tol = config.group_config.tolerance

    df = df.copy()

    # Start with an integer trigger marker/counter to avoid bool->int dtype writes.
    df['trigger'] = df[trigger].diff().abs().ge(tol).astype(int)
    # Count rows in between trigger changes
    for i in range(1, len(df)):
        if df['trigger'].iloc[i] == 1:
            df.loc[df.index[i], 'trigger'] = 1
        else:
            df.loc[df.index[i], 'trigger'] = int(df.loc[df.index[i - 1], 'trigger']) + 1

    # Calculate the mean values for the last 'group_time' rows of each group where trigger is equal or greater than trigger_steps
    grouped_data = []
    grouped_std = []
    grouped_index = []
    full_df = df
    df = df[df['trigger'] >= trigger_steps]
    # Check if there are any resets, if not, throw an error
    if df.empty:
        raise ValueError("No trigger found. Please check the configuration.")
    # Get indices of all rows where trigger is smaller than in the previous row
    resets = df.index[df['trigger'].diff() < 0].tolist()

    # Group the last `group_time` index units of each step, the last step has no reset
    group_ends = [df.index[df.index < reset][-1] for reset in resets] + [df.index[-1]]
    for prev_index in group_ends:
        group = full_df[(full_df.index > prev_index - group_time) & (full_df.index <= prev_index)]
        grouped_data.append(group.mean())
        grouped_std.append(group.std(ddof=1))
        grouped_index.append(prev_index)

    # Create a new DataFrame from the grouped data and keep source time index
    grouped_df = pd.DataFrame(grouped_data, index=grouped_index)
    std_df = pd.DataFrame(grouped_std, index=grouped_index)
    # Rename columns to match the original DataFrame
    grouped_df.columns = df.columns
    std_df.columns = df.columns
    grouped_df = grouped_df.drop(columns='trigger')
    std_df = std_df.drop(columns='trigger')

    if group_duplicates:
        trigger_col = config.group_config.trigger
        ordered = grouped_df.sort_values(trigger_col)
        vals = ordered[trigger_col].to_numpy()
        cluster = np.zeros(len(vals), dtype=int)
        ref = vals[0]
        cid = 0
        for i in range(1, len(vals)):
            if np.isclose(vals[i], ref, rtol=rtol, atol=0.0):
                cluster[i] = cid
            else:
                cid += 1
                cluster[i] = cid
                ref = vals[i]
        ordered = ordered.assign(_cluster=cluster)
        # Preserve first source index of each cluster so reset_index=False stays meaningful.
        first_idx = ordered.groupby('_cluster').apply(lambda g: g.index[0], include_groups=False)
        grouped_df = ordered.groupby('_cluster').mean(numeric_only=False)
        grouped_df.index = first_idx.values
        grouped_df = grouped_df.sort_index()
        std_ordered = std_df.loc[ordered.index].assign(_cluster=cluster)
        std_df = std_ordered.groupby('_cluster').mean(numeric_only=False)
        std_df.index = first_idx.values
        std_df = std_df.sort_index()

    if reset_index:
        grouped_df = grouped_df.reset_index(drop=True)
        std_df = std_df.reset_index(drop=True)
    if return_std:
        return grouped_df, std_df
    return grouped_df


def group_data(config: ValidationConfig, df: pd.DataFrame) -> pd.DataFrame:
    """
    Groups the data in the DataFrame according to the group configuration.
    Create a new dataframe with the mean values of each group.
    Each group is calculated from the last `group_time` rows, from every step of `steps` and with an initial offset of `offset`.
    """
    group_time = config.group_config.group_time
    steps = config.group_config.steps
    offset = config.group_config.offset

    time_dif = int((len(df) - offset) / steps)

    print(f"Grouping data with group_time={group_time}, steps={steps}, offset={offset}, time_dif={time_dif}")

    # Calculate time intervals for grouping
    time_intervals = np.arange(offset, len(df), time_dif)

    grouped_data = []
    grouped_index = []
    for start in time_intervals:
        end = start + time_dif
        if end <= len(df):
            group = df.iloc[end - group_time:end]
            grouped_data.append(group.mean())
            # Keep the physical timestamp of the group end.
            grouped_index.append(df.index[end - 1])

    # Create a new DataFrame from the grouped data
    grouped_df = pd.DataFrame(grouped_data, index=grouped_index)

    # Rename columns to match the original DataFrame
    # grouped_df.columns = df.columns

    return grouped_df
