def _apply_elapsed_time_index(df: pd.DataFrame, time_axis: str | None) -> pd.DataFrame:
    """Use the seconds since the first sample as index, the samples are not equidistant."""
    if time_axis is None:
        return df

    if time_axis != 'elapsed':
        raise ValueError(f"data_source.time_axis must be 'elapsed', got {time_axis}")

    timestamps = pd.to_datetime(df['DateTime'])
    result_df = df.copy()
    result_df.index = (timestamps - timestamps.iloc[0]).dt.total_seconds().round(3).to_numpy()
    return result_df


def _apply_hold_time_index(df: pd.DataFrame, hold_time: float | int | None) -> pd.DataFrame:
    """Expand data to sample-and-hold timeline and assign dense time index.

    Example: 2 rows with hold_time=10 become 20 rows with index 1..20.
    """
    if hold_time is None:
        return df

    if hold_time <= 0:
        raise ValueError(f"data_source.hold_time must be > 0, got {hold_time}")

    if not float(hold_time).is_integer():
        raise ValueError(f"data_source.hold_time must be an integer for sample-and-hold expansion, got {hold_time}")

    steps = int(hold_time)
    if steps == 1:
        result_df = df.copy()
        result_df.index = np.arange(1, len(result_df) + 1, dtype=int)
        return result_df

    result_df = df.loc[df.index.repeat(steps)].reset_index(drop=True)
    result_df.index = np.arange(1, len(result_df) + 1, dtype=int)
    return result_df


