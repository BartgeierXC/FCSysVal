"""
Utility to convert a 2D lookup table (x, y, z) to a polynomial fit of degree `deg`.
Provides conv_lut_to_2Dpoly(x, y, z, deg) which returns a dict with the fitted
model, PolynomialFeatures transformer, coefficient matrix (shape (deg+1,deg+1)),
quality metrics and helper strings for Modelica usage.

This is a modular, testable re-implementation of the logic in
`scrpts/conv_cmp_csv_to_polynome.py`.

Author: generated by assistant
"""


def conv_lut_to_2Dpoly(x: np.ndarray, y: np.ndarray, z: np.ndarray, deg: int) -> Dict:
    """
    Fit a 2D polynomial z = f(x, y) of total degree `deg` to scattered data.

    Inputs:
    - x, y, z: 1-D numpy arrays of the same length N containing the sample points.
    - deg: non-negative integer polynomial degree (total degree for each variable).

    Returns a dictionary with keys:
    - "model": fitted sklearn LinearRegression instance (fit_intercept=False)
    - "poly": fitted sklearn PolynomialFeatures instance
    - "coef_matrix": numpy array shape (deg+1, deg+1) with coefficients c[i,j] for x**i * y**j
    - "r_squared": coefficient of determination on the training data
    - "rrmse": relative RMSE = sqrt(mean((z - z_pred)^2)) / mean(z)
    - "modelica_parameter": string ready to paste into a Modelica parameter declaration
    - "formula": human-readable (approx.) polynomial formula string

    The implementation sets LinearRegression(fit_intercept=False) and uses
    PolynomialFeatures(degree=deg, include_bias=True) so the constant term is
    part of the coefficient vector and maps directly to coef_matrix[0,0].
    """

    # Basic validation
    x = np.asarray(x).ravel()
    y = np.asarray(y).ravel()
    z = np.asarray(z).ravel()

    if x.shape != y.shape or x.shape != z.shape:
        raise ValueError("x, y and z must have the same shape")
    if deg < 0 or not isinstance(deg, int):
        raise ValueError("deg must be a non-negative integer")
    n_samples = x.size
    if n_samples == 0:
        raise ValueError("Input arrays must not be empty")

    # Remove samples where z is NaN (or x/y are NaN)
    mask = ~np.isnan(x) & ~np.isnan(y) & ~np.isnan(z)
    x = x[mask]
    y = y[mask]
    z = z[mask]
    if x.size == 0:
        raise ValueError("All samples are NaN after filtering")

    xy = np.vstack((x, y)).T

    poly = PolynomialFeatures(degree=deg, include_bias=True)
    xy_poly = poly.fit_transform(xy)

    # Use fit_intercept=False because the polynomial feature matrix already contains the bias (constant) column
    model = LinearRegression(fit_intercept=False)
    model.fit(xy_poly, z)

    z_pred = model.predict(xy_poly)

    # Build coefficient matrix c[i,j] where i is power of x, j is power of y
    nx = deg + 1
    ny = deg + 1
    c = np.zeros((nx, ny), dtype=float)

    # poly.powers_ lists the exponents for each feature column in the same order as xy_poly
    powers = poly.powers_  # shape (n_features, 2)
    coefs = model.coef_

    if powers.shape[0] != coefs.shape[0]:
        # should not happen, but guard
        raise RuntimeError("Mismatch between feature powers and coefficients")

    for coef, (i, j) in zip(coefs, powers):
        if i <= deg and j <= deg:
            c[i, j] = float(coef)

    # Quality metrics
    # r_squared: use sklearn-style score on training data
    # When fit_intercept=False we cannot use model.score directly with original xy_poly because score uses self._residues; but LinearRegression.score works fine.
    r_squared = model.score(xy_poly, z)
    rrmse = float(np.sqrt(np.mean((z - z_pred) ** 2)) / (np.mean(z) if np.mean(z) != 0 else 1.0))

    # Create a readable polynomial formula (truncated)
    terms = []
    for i in range(nx):
        for j in range(ny):
            coef = c[i, j]
            if np.isclose(coef, 0.0):
                continue
            term = f"{coef:.6g}"
            if i > 0:
                term += f"*x"
                if i > 1:
                    term += f"^{i}"
            if j > 0:
                term += f"*y"
                if j > 1:
                    term += f"^{j}"
            terms.append(term)
    formula = " + ".join(terms) if terms else "0"

    # Modelica parameter formatting (rows = x-power index, columns = y-power index)
    rows = []
    for row in c:
        formatted_row = ", ".join([f"{val:.6g}" for val in row])
        rows.append(formatted_row)
    modelica_parameter = f"parameter Real c[{c.shape[0]},{c.shape[1]}] = [{'; '.join(rows)}];"

    # Format for np.polynomial.polynomial.polyval2d
    # polyval2d expects c as a 2D array where c[i,j] is the coefficient of x**i * y**j
    polyval2d_coef = c.copy()
    polyval2d_coef_str = repr(polyval2d_coef)

    return {
        "model": model,
        "poly": poly,
        "coef_matrix": c,
        "polyval2d_coef": polyval2d_coef,
        "polyval2d_coef_str": polyval2d_coef_str,
        "r_squared": float(r_squared),
        "rrmse": rrmse,
        "modelica_parameter": modelica_parameter,
        "formula": formula,
    }


def _apply_conditions_to_df(df: pd.DataFrame, conditions: list | None) -> pd.DataFrame:
    """Apply SQL-style WHERE conditions to a DataFrame via pandas query.

    Supported SQL syntax (case-insensitive):
      - Comparisons : ``>``, ``<``, ``>=``, ``<=``, ``!=``, ``=``
      - IN list     : `` `col` IN (1, 2, 3) ``
      - NOT IN      : `` `col` NOT IN (1, 2, 3) ``
      - BETWEEN     : `` `col` BETWEEN 20 AND 80 ``
      - IS NOT NULL : `` `col` IS NOT NULL ``
      - IS NULL     : `` `col` IS NULL ``
      - Backtick-quoted column names with spaces/special chars are supported.
    """
    import re

    if not conditions:
        return df

    for condition in conditions:
        q = condition.strip()

        # NOT IN (...) → not in [...]  (must come before IN to avoid partial match)
        q = re.sub(
            r'\bNOT\s+IN\s*\(([^)]*)\)',
            lambda m: f'not in [{m.group(1)}]',
            q, flags=re.IGNORECASE
        )
        # IN (...) → in [...]
        q = re.sub(
            r'\bIN\s*\(([^)]*)\)',
            lambda m: f'in [{m.group(1)}]',
            q, flags=re.IGNORECASE
        )
        # `col` BETWEEN lo AND hi  →  `col` >= lo and `col` <= hi
        def _replace_between(m):
            col = m.group(1).strip()
            return f'{col} >= {m.group(2)} and {col} <= {m.group(3)}'
        q = re.sub(
            r'(.+?)\s+BETWEEN\s+(\S+)\s+AND\s+(\S+)',
            _replace_between,
            q, flags=re.IGNORECASE
        )
        # IS NOT NULL / IS NULL – pandas query does not support these directly;
        # drop affected rows via notna/isna before querying instead.
        for null_match in re.finditer(r'(`[^`]+`|\w+)\s+IS\s+(NOT\s+)?NULL', q, flags=re.IGNORECASE):
            col_raw = null_match.group(1).strip('`')
            is_not = bool(null_match.group(2))
            df = df[df[col_raw].notna()] if is_not else df[df[col_raw].isna()]
        q = re.sub(r'(`[^`]+`|\w+)\s+IS\s+(?:NOT\s+)?NULL', '', q, flags=re.IGNORECASE).strip()
        # Single = (not preceded by <, >, !, =) → ==
        q = re.sub(r'(?<![<>!=])=(?!=)', '==', q)

        df = df.query(q)

    return df


def _apply_time_window(df: pd.DataFrame, start_date, end_date) -> pd.DataFrame:
    """Keep the rows between start_date and end_date, both included, as the database query does."""
    if start_date is None and end_date is None:
        return df
    if 'DateTime' not in df:
        raise ValueError('A time window needs a DateTime column in the CSV source')
    stamps = pd.to_datetime(df['DateTime'])
    keep = pd.Series(True, index=df.index)
    if start_date is not None:
        keep &= stamps >= pd.Timestamp(start_date)
    if end_date is not None:
        keep &= stamps <= pd.Timestamp(end_date)
    window = df[keep].reset_index(drop=True)
    if window.empty:
        raise ValueError('No data found in the specified timeframe of the CSV source.')
    return window


def _csv_usecols(config: ValidationConfig):
    """Return a column filter for a CSV source with many signals, None if all columns are needed.

    Conditions may refer to further columns, so a run with conditions reads all columns.
    """
    if getattr(config.data_source, 'conditions', None):
        return None
    wanted = {'DateTime', *config.data_source.input_variables, *config.data_source.output_variables}
    return lambda column: column in wanted


def get_csv_source(config: ValidationConfig):
    df = pd.read_csv(config.data_source.csv_path, sep=config.data_source.csv_sep, encoding='utf-8',
                     usecols=_csv_usecols(config))
    df = _apply_time_window(df, getattr(config.data_source, 'start_date', None),
                            getattr(config.data_source, 'end_date', None))

    conditions = getattr(config.data_source, 'conditions', None)
    df = _apply_conditions_to_df(df, conditions)

    df = _apply_hold_time_index(df, getattr(config.data_source, 'hold_time', None))
    df = _apply_elapsed_time_index(df, getattr(config.data_source, 'time_axis', None))

    # Return two dataframes: one with input variables and one with output variables
    input_df = df[config.data_source.input_variables]
    output_df = df[config.data_source.output_variables]

    return input_df, output_df


def _apply_factors_and_offset(df: pd.DataFrame,
                              variables: list[str],
                              factors: list[float] | None,
                              offsets: list[float] | None,
                              context: str) -> pd.DataFrame:
    """Apply per-column affine transform: value = value * factor + offset."""
    result_df = df.copy()

    if factors is not None:
        if len(factors) != len(variables):
            raise ValueError(
                f"{context}: len(factors)={len(factors)} does not match len(variables)={len(variables)}"
            )
        result_df = result_df.mul(np.asarray(factors), axis=1)

    if offsets is not None:
        if len(offsets) != len(variables):
            raise ValueError(
                f"{context}: len(offsets)={len(offsets)} does not match len(variables)={len(variables)}"
            )
        result_df[variables] = result_df[variables].add(np.asarray(offsets), axis=1)

    return result_df


def _build_overwrite_config_from_sim_file(config: ValidationConfig, stop_time: float) -> list[dict[str, Any]]:
    """Build overwrite_config from simulation config and enforce stop_time consistency."""
    sim_cfg = parse_config(str(config.sim_config.config_path)) or {}

    simulation_setup = sim_cfg.get("simulation_setup") or {}
    if not isinstance(simulation_setup, dict):
        simulation_setup = {}
    else:
        simulation_setup = dict(simulation_setup)

    # If simulation_setup contains items which contain dictionarys, drop those items
    simulation_setup = {k: v for k, v in simulation_setup.items() if not isinstance(v, dict)}

    raw_stop_time = simulation_setup.get("stop_time")
    if raw_stop_time is None:
        simulation_setup["stop_time"] = stop_time
    else:
        simulation_setup["stop_time"] = float(raw_stop_time)

    sim_flags = sim_cfg.get("sim_flags") or []
    if not isinstance(sim_flags, list):
        sim_flags = [str(sim_flags)]
    else:
        sim_flags = [str(flag) for flag in sim_flags]

    sim_flags = [flag for flag in sim_flags if not flag.startswith("-stopTime=")]
    # sim_flags.append(f"-stopTime={simulation_setup['stop_time']}")

    return [
        {"sim_flags": sim_flags},
        {"simulation_setup": simulation_setup},
    ]


def prepare_sim_input(config: ValidationConfig, input_df, verbose=False):
    # Convert to OM CombiTable and write to file
    input_df = _apply_factors_and_offset(
        input_df,
        config.data_source.input_variables,
        config.data_source.input_factors,
        config.data_source.input_offset,
        context="data_source.input_*",
    )

    # Use the existing DataFrame index as simulation time axis.
    input_df = input_df.copy()
    input_df.index = pd.to_numeric(input_df.index, errors='raise')
    input_df = input_df.sort_index(kind='stable')
    input_df['time'] = input_df.index.to_numpy()
    df = input_df.set_index('time')

    if verbose:
        print("Simulation input DataFrame before transformation:")
        print(df.head())

    stop_time = float(df.index.max())

    lut_path = Path(config.sim_config.input_path)
    lut_path.parent.mkdir(parents=True, exist_ok=True)
    _export_lut(df, lut_path, "op_cons")

    return _build_overwrite_config_from_sim_file(config, stop_time)


def _export_lut(df: pd.DataFrame, lut_path: Path, table_name: str) -> None:
    rows, cols = df.shape
    header = [f"float {table_name}({rows},{cols + 1})"]
    body = [f"{idx} " + " ".join(str(val) for val in row.values) for idx, row in df.iterrows()]
    lut_path.write_text("#1\n" + "\n".join(header + body) + "\n", encoding="utf-8")


